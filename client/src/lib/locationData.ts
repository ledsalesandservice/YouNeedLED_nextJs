// Helper to generate a slug from a location name
function toSlug(name: string, stateAbbr: string): string {
  return `${name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/-+$/, "")}-${stateAbbr.toLowerCase()}`;
}

